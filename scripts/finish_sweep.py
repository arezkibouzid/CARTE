"""PRC fine-tuning sweep: pick the best run and write the report (used by scripts/finish_sweep.sh).

    python scripts/finish_sweep.py select --prc OUT/prc --tags finetuned s12k ...      -> OUT/prc/best.json
    python scripts/finish_sweep.py report --root OUT --doc docs/prc_sweep_results.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT = {"steps": 6000, "lr": 3e-4, "batch": 16}  # the first run ("finetuned") wrote no config file


def runs(prc: Path, tags) -> list[dict]:
    out = []
    for t in tags:
        sc = prc / t / "unet_scores.json"
        if not sc.exists():
            continue
        cfg = prc / f"prc_{t}_config.json"
        c = json.loads(cfg.read_text()) if cfg.exists() else dict(DEFAULT)
        out.append({"tag": t, **{k: c[k] for k in ("steps", "lr", "batch")}, **json.loads(sc.read_text())})
    return out


def curves(prc: Path) -> list[dict]:
    rows: dict = {}
    for f in sorted(prc.glob("checkpoints_*.jsonl")):
        for line in f.read_text().splitlines():
            if not line.strip():
                continue
            d = json.loads(line)
            rows.setdefault((d["tag"], d["step"]), []).append(d)
    out = []
    for (t, s), ds in sorted(rows.items()):
        if len(ds) < 4:
            continue
        w = [d["road_pixels_true"] for d in ds]
        m = lambda k: sum(d[k] * x for d, x in zip(ds, w)) / sum(w)
        out.append({"tag": t, "step": s, "road_auc": m("road_auc"), "road_iou": m("road_iou"), "importance_accuracy": m("importance_accuracy")})
    return out


def select(a):
    prc = Path(a.prc)
    rs = runs(prc, a.tags)
    best = max(rs, key=lambda r: (round(r["road_iou"], 4), r["importance_accuracy"]))
    (prc / "best.json").write_text(json.dumps({"best": best, "runs": rs}, indent=1), encoding="utf-8")
    print(best["tag"], best["steps"], best["lr"], best["batch"])


def table_lines(md: Path, skip_header_rows: int = 0) -> list[str]:
    import re

    if not md.exists():
        return [f"*(missing: `{md}`)*"]
    out = []
    for l in md.read_text(encoding="utf-8").splitlines():
        if l.startswith("|"):
            l = re.sub(r"\[(\d+)\]\(exercise_\d+/decision\.md\)", r"\1", l)  # links relative to the outputs folder
            out.append(l.replace(" alone alone", " alone"))
    return out


def report(a):
    root = Path(a.root)
    prc = root / "prc"
    b = json.loads((prc / "best.json").read_text())
    L = ["# PRC fine-tuning sweep, final model, and the exercises without BD TOPO or OSM", "",
         "*Generated by `scripts/finish_sweep.sh` (Slurm, unattended). Sheet `Hackathon_100K.tif`; every score is out of fold "
         "on the 4 x 4 blocks of `scan-learn`, except the final model (trained on every block, for sheets without labels).*", "",
         "## 1. Runs (two H100 per configuration, one fold per GPU)", "",
         "| run | steps | learning rate | batch | road AUC | road IoU | importance accuracy | importance 4 vs 5 | structure AUC |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in sorted(b["runs"], key=lambda r: -r["road_iou"]):
        star = "**" if r["tag"] == b["best"]["tag"] else ""
        L.append(f"| {star}{r['tag']}{star} | {r['steps']:,} | {r['lr']:g} | {r['batch']} | {r['road_auc']:.4f} | {star}{r['road_iou']:.4f}{star} | "
                 f"{r['importance_accuracy']:.1%} | {r['importance_4_vs_5_accuracy']:.1%} | {r['structure_auc']:.3f} |")
    L += ["", f"Best (road IoU, then importance): **{b['best']['tag']}**. It is the configuration of the final model.", "",
          "## 2. Held-out scores during training (mean of the 4 folds, weighted by road pixels)", "",
          "| run | step | road AUC | road IoU | importance accuracy |", "| --- | --- | --- | --- | --- |"]
    for c in curves(prc):
        L.append(f"| {c['tag']} | {c['step']:,} | {c['road_auc']:.4f} | {c['road_iou']:.4f} | {c['importance_accuracy']:.1%} |")
    L += ["", "The learning rate follows a one-cycle schedule, so a mid-run checkpoint is not the same as a shorter run; the curves show "
          "where the held-out road score stops improving.", "",
          "## 3. Routes against BD TOPO (101 town pairs, 150 random pairs): each run's network alone", ""]
    L += table_lines(root / "ablation_sweep" / "ablation.md")
    L += ["", "## 4. The 10 PDF exercises: each run's network against BD TOPO and OSM", ""]
    L += table_lines(root / "exercise_ablation_sweep" / "exercise_ablation.md")
    L += ["", f"## 5. The 10 exercises on the best run's network (out of fold, checked against BD TOPO and OSM)", "",
          f"Outputs: `{root / 'pdf_exercises_prc_best'}`.", ""]
    L += table_lines(root / "pdf_exercises_prc_best" / "summary.md")
    alt = root / "pdf_exercises_prc_s24k" / "summary.md"
    if alt.exists():
        L += ["", "## 5b. Alternative: the same exercises on the s24k run's network", "",
              f"Outputs: `{alt.parent}`. s24k is the worst run by pixel IoU and on the 251 route pairs, but the closest to BD TOPO on the "
              "10 exercises (section 4); see section 7.", ""]
        L += table_lines(alt)
    L += ["", "## 6. The 10 exercises from the scan and the PDF alone (no BD TOPO, no OSM)", "",
          f"The final model (`prc/prc_{b['best']['tag']}_final.pt`, every block) applied to the sheet by `prc_unet.py infer`, then "
          f"`pdf-exercises --network prc-alone` on a folder holding only the scan. Outputs: `{root / 'pdf_exercises_tif_only'}`. "
          "No check is possible without references; and since the final model saw this sheet's labels, these routes are not a measure "
          "of accuracy (sections 1-5 are).", ""]
    L += table_lines(root / "pdf_exercises_tif_only" / "summary.md")
    concl = Path(a.doc).with_suffix(".conclusion.md")
    if concl.exists():
        L += ["", concl.read_text(encoding="utf-8").strip()]
    doc = Path(a.doc)
    doc.write_text("\n".join(L) + "\n", encoding="utf-8")
    main = doc.parent / "prc_unet_and_pdf_exercises.md"
    if main.exists():
        t = main.read_text(encoding="utf-8")
        old = "is\nrunning; its results will be added here."
        if old in t:
            t = t.replace(old, f"ran\nunattended; results in [{doc.name}]({doc.name}) (best: **{b['best']['tag']}**, road IoU "
                               f"{b['best']['road_iou']:.3f}).")
            main.write_text(t, encoding="utf-8")
    print(f"report: {doc}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=("select", "report"))
    ap.add_argument("--prc")
    ap.add_argument("--tags", nargs="*")
    ap.add_argument("--root")
    ap.add_argument("--doc")
    a = ap.parse_args()
    {"select": select, "report": report}[a.cmd](a)
