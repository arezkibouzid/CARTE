"""Report of the PRC runs trained with an extra labelled sheet (Scenario 1), evaluated on the Hackathon sheet only.

    python scripts/finish_mix.py --root outputs/hackathon100k --tags finetuned mix6k mix12k mix24k_lr1e-4 --doc docs/prc_mix_results.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from finish_sweep import curves, runs, table_lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--tags", nargs="+", required=True)
    ap.add_argument("--doc", required=True)
    ap.add_argument("--best", required=True)
    a = ap.parse_args()
    root = Path(a.root)
    prc = root / "prc"
    rs = runs(prc, a.tags)
    base = next((r for r in rs if r["tag"] == "finetuned"), None)
    L = ["# PRC trained with a second sheet (Scenario 1), evaluated on the Hackathon sheet only", "",
         "*Generated by `scripts/finish_mix.sh` (Slurm). Training: the PRC weights fine-tuned on the 3 training folds of the Hackathon "
         "sheet plus every block of Scenario 1 (`examples/otherdata`, half of the training tiles). Evaluation: the held-out fold of the "
         "Hackathon sheet (out of fold, the same folds as before), then routes, the 10 exercises and the mismatch analysis on the "
         "`examples` data only. Scenario 1 is never used for evaluation.*", "",
         "## 1. Pixel scores on the Hackathon sheet (out of fold)", "",
         "| run | training data | steps | learning rate | road AUC | road IoU | importance accuracy | importance 4 vs 5 | structure AUC |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in sorted(rs, key=lambda r: -r["road_iou"]):
        cfg = prc / f"prc_{r['tag']}_config.json"
        extra = json.loads(cfg.read_text()).get("extra") if cfg.exists() else []
        data = "Hackathon + " + ", ".join(extra) if extra else "Hackathon only"
        star = "**" if r["tag"] == a.best else ""
        d = f" ({r['road_iou'] - base['road_iou']:+.3f})" if base and r is not base else ""
        L.append(f"| {star}{r['tag']}{star} | {data} | {r['steps']:,} | {r['lr']:g} | {r['road_auc']:.4f} | {r['road_iou']:.4f}{d} | "
                 f"{r['importance_accuracy']:.1%} | {r['importance_4_vs_5_accuracy']:.1%} | {r['structure_auc']:.3f} |")
    L += ["", f"Best (road IoU, then importance): **{a.best}**.", "",
          "## 2. Held-out scores during training (mean of the 4 folds)", "",
          "| run | step | road AUC | road IoU | importance accuracy |", "| --- | --- | --- | --- | --- |"]
    for c in curves(prc):
        if c["tag"] in a.tags:
            L.append(f"| {c['tag']} | {c['step']:,} | {c['road_auc']:.4f} | {c['road_iou']:.4f} | {c['importance_accuracy']:.1%} |")
    L += ["", "## 3. Routes against BD TOPO (101 town pairs, 150 random pairs): each network alone", ""]
    L += table_lines(root / "ablation_mix" / "ablation.md")
    L += ["", "## 4. The 10 PDF exercises against BD TOPO and OSM", ""]
    L += table_lines(root / "exercise_ablation_mix" / "exercise_ablation.md")
    L += ["", f"## 5. The 10 exercises on the best network ({a.best}, out of fold, checked)", "", f"Outputs: `{root / 'pdf_exercises_prc_mix_best'}`.", ""]
    L += table_lines(root / "pdf_exercises_prc_mix_best" / "summary.md")
    L += ["", f"## 6. Where the {a.best} routes differ from BD TOPO and OSM", "", f"Maps and GeoJSON: `{root / 'mismatch_prc_mix_best'}` (method: `prc_mismatch.md`).", ""]
    ms = root / "mismatch_prc_mix_best" / "mismatch_summary.md"
    if ms.exists():
        t = ms.read_text(encoding="utf-8")
        for head in ("## Per exercise", "## Causes", "## Gap points"):
            if head in t:
                part = t.split(head, 1)[1].split("\n## ", 1)[0]
                L += [f"### {head[3:]}", ""] + [l for l in part.splitlines() if l.startswith("|")] + [""]
    tif = root / "pdf_exercises_tif_only_mix" / "summary.md"
    if tif.exists():
        L += ["## 7. From the scan and the PDF alone (no BD TOPO, no OSM), final model of the best run", ""] + table_lines(tif)
    Path(a.doc).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"report: {a.doc}")


if __name__ == "__main__":
    main()
