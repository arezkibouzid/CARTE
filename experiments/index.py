"""Write experiments/INDEX.md: every run of experiments/runs (status, time, energy, commit, files) and the earlier
experiments kept under outputs/ with the report that describes each of them. Read-only on the runs.

    .venv/bin/python experiments/index.py
"""
from __future__ import annotations

import json
from pathlib import Path

from common import REPO, RUNS

# earlier experiments (before this framework): output folder -> report
LEGACY = [
    ("outputs/hackathon100k/ablation*, exercise_ablation*", "docs/corrector_route_impact.md, docs/corrector_pricing_results.md",
     "corrector (with / without), U-Net, pricing of uncertain roads on the 10 exercises"),
    ("outputs/hackathon100k/learn_*", "docs/corrector_route_gate_ablation.md, docs/corrector_closer_to_bdtopo.md",
     "corrector components: CNN, geometry, route gate, removal"),
    ("outputs/hackathon100k/prc/ (fold models, checkpoints_*.jsonl, logs/)", "docs/prc_unet_and_pdf_exercises.md, docs/prc_sweep_results.md",
     "PRC U-Net zero-shot vs fine-tuned, step / learning-rate / batch sweep"),
    ("outputs/hackathon100k/prc/mix*, ablation_mix, exercise_ablation_mix", "docs/prc_mix_results.md", "second training sheet (Scenario 1)"),
    ("outputs/hackathon100k/ablation_loss, exercise_ablation_loss, mismatch_loss_*", "docs/prc_loss_results.md", "Dice / BCE weight ablation"),
    ("outputs/hackathon100k/ablation_robust, exercise_ablation_robust", "docs/prc_robust_results.md", "clDice and uncertainty-guided hard sampling"),
    ("outputs/hackathon100k/ablation_inference, ablation_tta2, mismatch_inference_*", "docs/prc_inference.md", "TTA and overlapping tiles, timing and hardware"),
    ("outputs/hackathon100k/ablation_retrace, bridge_check_*, mismatch_retrace_*", "docs/prc_retrace_results.md", "gap bridging and hysteresis tracing"),
    ("outputs/hackathon100k/ablation_cal, exercise_ablation_cal, prc/mix12k_cal", "docs/prc_calibration.md", "probability calibration"),
    ("outputs/hackathon100k/mismatch_*", "docs/prc_mismatch.md, docs/prc_uncertainty.md", "where routes differ from BD TOPO / OSM, uncertainty maps"),
    ("outputs/hackathon100k/coverage_precision.json", "docs/prc_best_config.md", "best configuration for coverage vs precision, with / without TTA"),
]


def main():
    rows = []
    for d in sorted(RUNS.glob("*")):
        if not d.is_dir():
            continue
        cfg = json.loads((d / "config.json").read_text()) if (d / "config.json").exists() else {}
        env = json.loads((d / "environment.json").read_text()) if (d / "environment.json").exists() else {}
        res = json.loads((d / "resources.json").read_text()) if (d / "resources.json").exists() else {}
        n = 0
        if (d / "metrics.json").exists():
            n = len(json.loads((d / "metrics.json").read_text()).get("records", []))
        files = ", ".join(sorted(p.name for p in d.glob("*.png")))
        energy = res.get("cpu_energy_j")
        g = res.get("gpu_energy_j")
        rows.append(f"| `{d.name}` | {res.get('status', 'running?')} | {cfg.get('script', '?').split('/')[-1]} "
                    f"{' '.join(cfg.get('tests', []) or cfg.get('groups', []) or [])}{' (quick)' if cfg.get('quick') else ''} | {n} | "
                    f"{res.get('wall_s', '—')} | {res.get('peak_rss_mb', '—')} | {energy if energy is not None else '—'} ({res.get('cpu_energy_method', '')})"
                    f"{f' + GPU {g}' if g else ''} | {env.get('host', '')} {('job ' + env['slurm_job']) if env.get('slurm_job') else ''} | "
                    f"{(env.get('git') or {}).get('commit', '')[:7]}{' +dirty' if (env.get('git') or {}).get('dirty') else ''} | {files} |")
    L = ["# Experiment index", "",
         "Generated by `experiments/index.py`. Every run is a folder of `experiments/runs/` that is never overwritten "
         "(config, environment, log, metrics, resources, figures); quick runs (`_quick`) and the first `routing_ablation` "
         "(exercise 1 only) are smoke tests of the scripts; the two failed quick runs stopped on bugs fixed before the full runs. "
         "Runs marked `+dirty` (13 Nov 2026) used commit 6ff7618 plus the changes committed with `experiments/`; later runs "
         "keep their uncommitted diff in `code.diff`.", "",
         "Derived analyses (each names its source run): " + ", ".join(f"`analysis/{f.name}`" for f in sorted((REPO / "experiments" / "analysis").glob("*"))), "",
         "| run | status | script / scope | records | wall (s) | peak RAM (MB) | CPU energy (J) | host | commit | figures |",
         "|---|---|---|---|---|---|---|---|---|---|", *rows, "",
         "## Earlier experiments (kept in `outputs/`, reported in `docs/`)", "",
         "| outputs | report | what |", "|---|---|---|", *[f"| {a} | {b} | {c} |" for a, b, c in LEGACY], ""]
    (REPO / "experiments" / "INDEX.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
